import pandas as pd
import numpy as np
import re

def clean_supplier_name(name):
    """
    Функция для нормализации и исправления наименований поставщиков.
    """
    if pd.isna(name):
        return name
    
    # 1. Базовая нормализация: верхний регистр, удаление лишних пробелов и точек в конце
    name = str(name).upper().strip()
    name = re.sub(r'\s+', ' ', name)  # Заменяем множественные пробелы на один
    name = name.rstrip('.')           # Удаляем точку в конце строки
    
    # 2. Словарь прямых замен для известных ошибок (после базовой нормализации)
    direct_mapping = {
        'ООО МИАНТ': 'МИАНТ',
        'ОООМИАНТ': 'МИАНТ',
        'МИАНТ.': 'МИАНТ',
        'ПАРТНЁР': 'ПАРТНЕР',
        'ООО ПАРТНЕР': 'ПАРТНЕР',
        'ООО ПАРТНЕР.': 'ПАРТНЕР',
        'ООО ВЖИК': 'ВЖИК',
        'ВЖК': 'ВЖИК',
        'ДЕЛ ЛИН': 'ДЕЛОВЫЕ ЛИНИИ',
        'ДЕЛ ЛИН.': 'ДЕЛОВЫЕ ЛИНИИ',
        'ДЕЛОВЫЕ ЛИНИИ.': 'ДЕЛОВЫЕ ЛИНИИ',
        'ЧАСНОЕ ЛИЦО': 'ЧАСТНОЕ ЛИЦО',
        'ЧАСНЫЙ': 'ЧАСТНОЕ ЛИЦО',
        'Ч. Л.': 'ЧАСТНОЕ ЛИЦО',
        'КСЕ': 'КСЭ',
        'ВСЕ ИНСТРУМЕНЫ': 'ВСЕ ИНСТРУМЕНТЫ',
        'СДЕК': 'СДЭК',
        'ЭТМ.': 'ЭТМ',
        'ЭТН': 'ЭТМ',
        'ЭТН.': 'ЭТМ'
    }
    
    # Если точное совпадение есть в словаре, возвращаем исправленный вариант
    if name in direct_mapping:
        return direct_mapping[name]
    
    # 3. Дополнительная очистка для случаев, когда "ООО" написано слитно или с пробелами перед названием
    name = re.sub(r'^ООО\s*', '', name).strip()
    if name in ['МИАНТ', 'ПАРТНЕР', 'ВЖИК']:
        return name
        
    return name

def process_vehicle_registry(input_file, output_file):
    print(f"Чтение файла: {input_file}...")
    
    # Читаем Excel. skiprows=0 можно изменить, если в файле есть лишние строки в начале
    df = pd.read_excel(input_file)
    
    # Очищаем названия колонок от случайных пробелов
    df.columns = df.columns.str.strip()
    
    print("Выполняется нормализация наименований поставщиков...")
    # 1. Нормализация текста и исправление ошибок
    df['Наименование поставщика'] = df['Наименование поставщика'].apply(clean_supplier_name)
    
    print("Преобразование дат...")
    # 2. Унификация дат в формат YYYY-MM-DD
    # dayfirst=False используется, так как в исходных данных формат "1/3/26" соответствует 3 января (M/D/YY), 
    # что подтверждается колонкой "Дата выезда" (03.01.2026).
    df['Дата'] = pd.to_datetime(df['Дата'], dayfirst=False, errors='coerce').dt.strftime('%Y-%m-%d')
    df['Дата выезда'] = pd.to_datetime(df['Дата выезда'], dayfirst=True, errors='coerce').dt.strftime('%Y-%m-%d')
    
    print("Обработка числовых данных и создание новых признаков...")
    # Преобразуем количественные колонки в числовой тип, заменяя ошибки и пропуски на 0
    qty_cols = ['Кол-во паллет', 'Кол-во упаковок', 'Кол-во коробок']
    for col in qty_cols:
        df[col] = pd.to_numeric(df[col], errors='coerce').fillna(0).astype(int)
        
    # 3. Feature Engineering: Тип операции
    df['Тип операции'] = np.where(
        (df['Кол-во паллет'] + df['Кол-во упаковок'] + df['Кол-во коробок']) > 0,
        'Погрузка',
        'Разгрузка'
    )
    
    # 4. Feature Engineering: День недели, Месяц, Квартал
    # Используем надежное маппинг-словарь для дней недели, чтобы не зависеть от локали системы
    days_map = {
        0: 'Понедельник', 1: 'Вторник', 2: 'Среда',
        3: 'Четверг', 4: 'Пятница', 5: 'Суббота', 6: 'Воскресенье'
    }
    
    # Временно преобразуем обратно в datetime для извлечения атрибутов
    dates_dt = pd.to_datetime(df['Дата'], errors='coerce')
    
    df['День недели'] = dates_dt.dt.dayofweek.map(days_map)
    df['Месяц'] = dates_dt.dt.month
    df['Квартал'] = dates_dt.dt.quarter
    
    # Сортируем по дате для удобства просмотра (опционально)
    df = df.sort_values(by='Дата').reset_index(drop=True)
    
    # Сохранение результата
    print(f"Сохранение очищенного файла: {output_file}...")
    df.to_excel(output_file, index=False)
    print("✅ Обработка успешно завершена!")

# === Запуск скрипта ===
if __name__ == "__main__":
    # Укажите здесь точные имена ваших файлов
    INPUT_FILENAME = 'Реестр-автотранспорта-2026.xlsx'
    OUTPUT_FILENAME = 'Реестр_автотранспорта_очищенный.xlsx'
    
    try:
        process_vehicle_registry(INPUT_FILENAME, OUTPUT_FILENAME)
    except FileNotFoundError:
        print(f"❌ Ошибка: Файл '{INPUT_FILENAME}' не найден. Убедитесь, что он лежит в той же папке, что и скрипт.")
    except Exception as e:
        print(f"❌ Произошла ошибка при обработке: {e}")